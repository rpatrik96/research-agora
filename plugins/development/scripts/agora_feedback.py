def load_pending_cutoff(report: dict) -> str | None:
    """The cutoff recorded for this exact report, or None.

    None also covers a pending report written by an older client, where
    submission falls back to archiving the whole spool.
    """
    try:
        with open(pending_cutoff_path()) as f:
            record = json.load(f)
    except (OSError, json.JSONDecodeError):
        return None
    if not isinstance(record, dict) or record.get("report_id") != report.get(
        "report_id"
    ):
        return None
    cutoff = record.get("cutoff")
    return cutoff if isinstance(cutoff, str) else None


def cmd_enable() -> int:
    config = load_config()
    if not config.get("installation_id"):
        config["installation_id"] = secrets.token_hex(16)
    config.update(
        {
            "enabled": True,
            "sink": config.get("sink", "github-issue"),
            "created": config.get("created", date.today().isoformat()),
        }
    )
    save_config(config)
    print(
        "Agora feedback capture ENABLED (local only — nothing is ever sent automatically)."
    )
    print(f"  config: {config_path()}")
    print(f"  spool:  {spool_path()}")
    print(
        f"  installation_id: {config['installation_id']} (random; reset by deleting the config)"
    )
    return 0


def cmd_disable() -> int:
    config = load_config()
    config["enabled"] = False
    save_config(config)
    # The capture hook is the throttled pruner, and it stops running here, so
    # enforce retention once on the way out (finding 6).
    prune_spool()
    print(
        "Agora feedback capture disabled. Existing spool kept; run 'purge' to delete it."
    )
    return 0


def cmd_status() -> int:
    config = load_config()
    # Unthrottled: status is a user-invoked command, not the hook, and the
    # count it prints should describe what is actually on disk.
    prune_spool()
    events = read_spool()
    print(f"enabled:            {config.get('enabled', False)}")
    print(
        f"kill switch:        {'AGORA_FEEDBACK=0 (capture disabled)' if kill_switch_active() else 'not set'}"
    )
    print(
        f"submissions:        {'disabled (CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1)' if submissions_disabled() else 'allowed after review'}"
    )
    print(f"sink:               {config.get('sink', 'github-issue')}")
    print(f"spool events:       {len(events)} ({spool_path()})")
    print(f"pending report:     {'yes' if load_pending() else 'no'}")
    return 0


def cmd_stats() -> int:
    agg = aggregate_spool(read_spool())
    if not agg["skills"]:
        print("Spool is empty — no Agora skill usage captured yet.")
        return 0
    print(
        f"Local usage {agg['from']} → {agg['to']} ({agg['sessions']} sessions). Nothing here has been sent anywhere.\n"
    )
    print(f"{'skill':<32} {'calls':>5} {'ok':>4} {'part':>4} {'err':>4}")
    for name in sorted(agg["skills"], key=lambda n: -agg["skills"][n]["invocations"]):
        o = agg["skills"][name]["outcomes"]
        print(
            f"{name:<32} {agg['skills'][name]['invocations']:>5} "
            f"{o.get('success', 0):>4} {o.get('partial', 0):>4} {o.get('error', 0):>4}"
        )
    return 0


def cmd_report() -> int:
    events = read_spool()
    report = build_report(events)
    if not report["skills"]:
        print("Spool is empty — nothing to report.")
        return 1
    existing = load_pending()
    if existing:  # keep user-curated insights across rebuilds
        insights = {
            e["skill"]: e.get("insights", []) for e in existing.get("skills", [])
        }
        for entry in report["skills"]:
            entry["insights"] = insights.get(entry["skill"], [])
    save_pending(report)
    save_pending_cutoff(report, events_cutoff(events))
    print(json.dumps(report, indent=2))
    print(f"\nPending report written to {pending_report_path()}", file=sys.stderr)
    print(
        "Add insights with: insight add <skill> <type> <text> [--confidence X]",
        file=sys.stderr,
    )
    return 0


def cmd_insight(args: argparse.Namespace) -> int:
    report = load_pending()
    if report is None:
        print("No pending report. Run 'report' first.")
        return 1
    if args.insight_action == "list":
        for entry in report["skills"]:
            for i, insight in enumerate(entry.get("insights", [])):
                print(f"{entry['skill']}[{i}] ({insight['type']}): {insight['text']}")
        return 0
    entries = {e["skill"]: e for e in report["skills"]}
    if args.skill not in entries:
        print(
            f"Skill '{args.skill}' is not in the pending report ({', '.join(sorted(entries))})."
        )
        return 1
    if args.insight_action == "add":
        if args.type not in INSIGHT_TYPES:
            print(f"Invalid type '{args.type}'. Valid: {', '.join(INSIGHT_TYPES)}")
            return 1
        text = args.text.strip()[:INSIGHT_TEXT_MAX]
        if CONTROL_CHARS_RE.search(text):
            # Rejected outright rather than warned about, unlike the PII
            # patterns: no insight needs a terminal escape or a NUL, the
            # aggregator discards the whole report over one, and `insight
            # list` would print it raw to a terminal (finding 3).
            print(
                "Rejected: insight text contains control characters "
                "(terminal escapes or NUL). Retype it as plain text."
            )
            return 1
        insight = {"type": args.type, "text": text, "confidence": args.confidence}
        entries[args.skill].setdefault("insights", []).append(insight)
        for label, pattern in PII_PATTERNS:
            if pattern.search(text):
                print(
                    f"WARNING: insight text contains a possible {label} — submit will block on it."
                )
    elif args.insight_action == "remove":
        insights = entries[args.skill].get("insights", [])
        if not 0 <= args.index < len(insights):
            print(f"No insight at index {args.index} for '{args.skill}'.")
            return 1
        insights.pop(args.index)
    save_pending(report)
    print("Pending report updated.")
    return 0


def archive_spool(cutoff: str | None = None) -> None:
    """Archive the events the submitted report covered, keeping the rest.

    Moving the whole spool swept every event captured between building the
    report and confirming the submission: they were archived without ever
    appearing in a submitted report, so the next report under-counted them
    (finding 7). Events newer than the cutoff stay live for the next cycle.

    A missing cutoff (a pending report from an older client) falls back to
    archiving everything, the prior behaviour: under-counting a handful of
    in-between events beats re-reporting events the aggregate already holds.
    """
    spool = spool_path()
    if not spool.exists():
        return
    secure_mkdir(archive_dir())
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    destination = archive_dir() / f"events-{stamp}.jsonl"
    if cutoff is None:
        shutil.move(str(spool), str(destination))
        return

    archived = []
    kept = []
    for line in spool.read_text().splitlines():
        if not line.strip():
            continue
        try:
            ts = json.loads(line).get("ts")
        except json.JSONDecodeError:
            ts = None
        # A line with no usable timestamp can never enter a report, so it is
        # archived rather than kept live forever.
        if isinstance(ts, str) and ts > cutoff:
            kept.append(line)
        else:
            archived.append(line)
    with open(destination, "a") as f:
        f.write("".join(f"{line}\n" for line in archived))
    write_spool_lines(kept)


def issue_body(report: dict) -> str:
    return (
        "Automated skill-feedback report (RFC-0001). Reviewed and submitted by the reporter.\n\n"
        "```json\n" + json.dumps(report, indent=2) + "\n```\n"
    )


def payload_digest(report: dict) -> str:
    """SHA-256 of the exact issue body this report would be submitted as.

    The confirmation token commits to this digest, so the payload the user
    reviewed is provably the payload that gets sent.
    """
    return hashlib.sha256(issue_body(report).encode("utf-8")).hexdigest()


def record_submit_token(report: dict) -> None:
    """Record that this exact payload was printed for review (finding 4)."""
    secure_mkdir(reports_dir())
    token = {
        "report_id": report["report_id"],
        "payload_sha256": payload_digest(report),
        "issued": int(time.time()),
    }
    with open(submit_token_path(), "w") as f:
        json.dump(token, f, indent=2)


def submit_token_refusal(report: dict) -> str | None:
    """None when a fresh review of this exact payload authorizes the send.

    Otherwise the reason to refuse. The preview-then-confirm gate of
    RFC-0001 §4.2 and §8 was prose only: cmd_submit printed the payload and
    then read the flag, so a bare ``submit --confirm`` printed and sent in
    one invocation, with nothing binding a prior review to a later
    confirmation. The token makes the two invocations structurally separate.
    Binding it to the payload digest means an edited report needs a new
    review; the TTL means a review from hours ago cannot authorize a send.
    """
    try:
        with open(submit_token_path()) as f:
            token = json.load(f)
    except (OSError, json.JSONDecodeError):
        return "no reviewed payload on record"
    if not isinstance(token, dict):
        return "the confirmation record is unreadable"
    if token.get("report_id") != report.get("report_id"):
        return "the reviewed payload belonged to a different report"
    if token.get("payload_sha256") != payload_digest(report):
        return "the report changed after it was reviewed"
    issued = token.get("issued")
    if isinstance(issued, bool) or not isinstance(issued, (int, float)):
        return "the confirmation record has no usable timestamp"
    age = time.time() - issued
    if age < 0 or age > SUBMIT_TOKEN_TTL_SECONDS:
        return (
            f"the review is stale (older than {SUBMIT_TOKEN_TTL_SECONDS // 60} minutes)"
        )
    return None


def cmd_submit(confirm: bool, allow_pii: bool) -> int:
    report = load_pending()
    if report is None:
        print("No pending report. Run 'report' first, review it, then submit.")
        return 1

    findings = pii_findings(report)
    if findings and not allow_pii:
        print("Submission BLOCKED — possible personal data in insights:")
        for finding in findings:
            print(f"  - {finding}")
        print(
            "Edit the insights (insight remove/add) or re-run with --allow-pii to override."
        )
        return 1

    control = control_char_findings(report)
    if control:
        print("Submission BLOCKED — control characters in the payload:")
        for finding in control:
            print(f"  - {finding}")
        print(
            "Rewrite the affected text as plain text. --allow-pii does not "
            "override this, and the aggregator rejects such a report anyway."
        )
        return 1

    report["consent"]["reviewed"] = True
    print("=== EXACT PAYLOAD TO BE SUBMITTED ===")
    print(json.dumps(report, indent=2))
    print("=====================================")

    if not confirm:
        record_submit_token(report)
        print(
            "\nNothing was sent. Review the payload above; to send exactly it, re-run "
            f"within {SUBMIT_TOKEN_TTL_SECONDS // 60} minutes: submit --confirm"
        )
        return 0
    # Kill switches outrank everything, including the state of the review
    # gate, so they answer first (RFC-0001 §8).
    if submissions_disabled():
        print("Submission refused: CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1 is set.")
        return 1
    if kill_switch_active():
        print("Submission refused: AGORA_FEEDBACK=0 is set.")
        return 1
    refusal = submit_token_refusal(report)
    if refusal:
        print(f"Submission refused: {refusal}.")
        print(
            "Run 'submit' first, read the exact payload it prints, then re-run "
            "'submit --confirm' to send that payload. Nothing was sent."
        )
        return 1

    save_pending(report)
    body = issue_body(report)
    title = f"[Feedback] {report['report_id']} ({report['period']['from']} → {report['period']['to']})"
    base_cmd = [
        "gh",
        "issue",
        "create",
        "--repo",
        HUB_REPO,
        "--title",
        title,
        "--body",
        body,
    ]
    result = None
    # First try with the label; if that fails (e.g. label missing in the
    # repo), retry unlabeled — the aggregator's title-prefix is not enough,
    # but a maintainer can label it, and losing the report entirely is worse.
    for cmd in (base_cmd + ["--label", ISSUE_LABEL], base_cmd):
        try:
            result = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
        except (OSError, subprocess.SubprocessError):
            result = None
        if result is not None and result.returncode == 0:
            break

    if result is not None and result.returncode == 0:
        receipt = result.stdout.strip()
        print(f"Submitted: {receipt}")
    else:
        manual = reports_dir() / f"submit-{report['report_id']}.md"
        manual.write_text(body)
        print("Could not submit via the GitHub CLI (gh). Manual fallback:")
        print(
            f"  1. Open https://github.com/{HUB_REPO}/issues/new?template=skill-feedback.yml"
        )
        print(f"  2. Paste the contents of {manual}")
        print(
            "The spool was NOT archived; re-run submit --confirm after posting "
            "(run 'submit' again first if the review window has lapsed), or "
            "archive manually."
        )
        return 1

    archive_spool(load_pending_cutoff(report))
    submitted = reports_dir() / f"submitted-{report['report_id']}.json"
    shutil.move(str(pending_report_path()), str(submitted))
    # The review authorized this one send: consume it, and drop the coverage
    # mark with the report it belonged to.
    for path in (submit_token_path(), pending_cutoff_path()):
        try:
            path.unlink()
        except OSError:
            pass
    print(f"Spool archived; report stored at {submitted}")
    return 0


def purge_unknown_skills() -> int:
    """Drop spool events and pending-report entries for non-Agora skills.

    Repairs a spool written while the registry filter was disabled, without
    discarding the legitimate history alongside it.
    """
    known = known_skill_names()
    if not known:
        print(
            "No skill name list available — refusing to purge, since every "
            "skill would count as unknown."
        )
        return 1

    dropped: dict[str, int] = {}
    spool = spool_path()
    if spool.exists():
        kept_lines = []
        for line in spool.read_text().splitlines():
            if not line.strip():
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                continue
            skill = event.get("skill")
            if skill is not None and skill not in known:
                dropped[skill] = dropped.get(skill, 0) + 1
                continue
            kept_lines.append(line)
        write_spool_lines(kept_lines)

    report_path = pending_report_path()
    if report_path.exists():
        try:
            report = json.loads(report_path.read_text())
        except json.JSONDecodeError:
            report = None
        if report is not None:
            entries = [e for e in report.get("skills", []) if e.get("skill") in known]
            if len(entries) != len(report.get("skills", [])):
                report["skills"] = entries
                report_path.write_text(json.dumps(report, indent=2) + "\n")
                print("Pending report rewritten without the unknown skills.")

    if dropped:
        summary = ", ".join(
            f"{name} ({count})" for name, count in sorted(dropped.items())
        )
        print(f"Dropped {sum(dropped.values())} event(s) for unknown skills: {summary}")
    else:
        print("No unknown-skill events in the spool.")
    return 0


def cmd_purge(unknown_only: bool = False) -> int:
    if unknown_only:
        return purge_unknown_skills()
    removed = []
    for path in (spool_path().parent, reports_dir()):
        if path.exists():
            shutil.rmtree(path)
            removed.append(str(path))
    print("Purged: " + (", ".join(removed) if removed else "nothing to remove"))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("capture", "enable", "disable", "status", "stats", "report"):
        sub.add_parser(name)
    purge = sub.add_parser("purge")
    purge.add_argument(
        "--unknown-skills",
        action="store_true",
        help="drop only events for skills outside the registry, keeping the rest",
    )
    submit = sub.add_parser("submit")
    submit.add_argument("--confirm", action="store_true")
    submit.add_argument("--allow-pii", action="store_true")
    insight = sub.add_parser("insight")
    insight_sub = insight.add_subparsers(dest="insight_action", required=True)
    insight_sub.add_parser("list")
    add = insight_sub.add_parser("add")
    add.add_argument("skill")
    add.add_argument("type")
    add.add_argument("text")
    add.add_argument("--confidence", type=float, default=0.5)
    remove = insight_sub.add_parser("remove")
    remove.add_argument("skill")
    remove.add_argument("index", type=int)

    args = parser.parse_args(argv)
    if args.command == "capture":
        return cmd_capture()
    if args.command == "enable":
        return cmd_enable()
    if args.command == "disable":
        return cmd_disable()
    if args.command == "status":
        return cmd_status()
    if args.command == "stats":
        return cmd_stats()
    if args.command == "report":
        return cmd_report()
    if args.command == "insight":
        return cmd_insight(args)
    if args.command == "submit":
        return cmd_submit(confirm=args.confirm, allow_pii=args.allow_pii)
    if args.command == "purge":
        return cmd_purge(unknown_only=args.unknown_skills)
    return 2


if __name__ == "__main__":
    sys.exit(main())
