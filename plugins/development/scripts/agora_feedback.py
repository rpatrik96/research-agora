# PII lint: block emails, home paths, and URLs carrying credential-shaped
# query parameters from ever entering a report.
#
# The home-directory pattern accepts any Windows drive letter and matches
# case-insensitively like the URL pattern beside it: hardcoding C: and
# matching case-sensitively let `D:\Users\...` and `/users/...` through
# unflagged (finding 5).
#
# The URL pattern allows word characters, dots, and hyphens around the
# credential keyword, because the real OAuth and API conventions are compound
# names. Requiring the keyword to sit immediately after ? or & caught only
# bare `?token=` and passed `?access_token=`, `?api_key=`, `?client_secret=`,
# and `?auth_token=` (finding 2). Substring matching also flags innocent
# parameters that contain a keyword (`?monkey=`), which is the right way to
# be wrong here: the finding is a warning at insight-add time and a block at
# submit that --allow-pii can override.
PII_PATTERNS = (
    ("email address", re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+")),
    (
        "home directory path",
        re.compile(r"(?:/home/|/Users/|[A-Za-z]:\\Users\\)\S+", re.I),
    ),
    (
        "URL with token-like query",
        re.compile(
            r"https?://\S*[?&][\w.-]*(?:token|key|secret|password|auth)[\w.-]*=", re.I
        ),
    ),
)

# Control characters never belong in a payload bound for a public issue.
# The aggregator rejects them (scripts/aggregate-feedback.py), but that runs
# weekly over already-published issues, so without a client-side check an
# ANSI escape or a NUL sits in a live public issue until then — and
# `insight list` prints insight text straight to a terminal (finding 3).
CONTROL_CHARS_RE = re.compile(r"[\x00-\x1f\x7f]")


