def registry_index_path() -> Path | None:
    """Locate registry/index.json across every layout the client ships in.

    A marketplace checkout (repo, or ~/.claude/plugins/marketplaces/<name>/)
    keeps the registry above the script, so walking up finds it. The plugin
    cache — ~/.claude/plugins/cache/<marketplace>/<plugin>/<version>/scripts/ —
    holds plugin directories only, and nothing above the script is the
    marketplace root; there we cross over to the sibling checkout by name.
    """
    here = Path(__file__).resolve()
    parents = list(here.parents)
    for parent in parents:
        candidate = parent / "registry" / "index.json"
        if candidate.is_file():
            return candidate
    for i, parent in enumerate(parents):
        if parent.name == "cache" and i > 0:
            candidate = (
                parent.parent
                / "marketplaces"
                / parents[i - 1].name
                / "registry"
                / "index.json"
            )
            if candidate.is_file():
                return candidate
    return None


def marketplace_root() -> Path | None:
    """Root of the marketplace checkout, when one is reachable."""
    index = registry_index_path()
    return index.parent.parent if index else None


def marketplace_manifest_path() -> Path | None:
    """Locate .claude-plugin/marketplace.json in the resolved checkout."""
    root = marketplace_root()
    if root is None:
        return None
    candidate = root / ".claude-plugin" / "marketplace.json"
    return candidate if candidate.is_file() else None


def load_skill_names(path: Path) -> set[str]:
    """Names from either a registry index or the shipped name manifest."""
    try:
        with open(path) as f:
            data = json.load(f)
    except (OSError, json.JSONDecodeError):
        return set()
    if isinstance(data, dict) and "repos" in data:
        try:
            return {
                s["name"]
                for repo in data.get("repos", [])
                for s in repo.get("skills", [])
            }
        except (KeyError, TypeError):
            return set()
    if isinstance(data, dict) and isinstance(data.get("names"), list):
        return {n for n in data["names"] if isinstance(n, str)}
    return set()


_KNOWN_SKILLS: set[str] | None = None


def known_skill_names() -> set[str]:
    """Skill and agent names this marketplace owns.

    Fails CLOSED: an unresolvable registry yields an empty set, so capture
    records nothing rather than everything. The reverse — recording any skill
    invocation when the registry is missing — leaked personal and third-party
    skill names into public reports from the plugin-cache layout, where the
    registry never resolved (issue #25).

    Sources, in order: an explicit AGORA_SKILL_NAMES_FILE override (tests),
    the marketplace registry, then skill-names.json shipped beside this script
    so the cache layout has a list of its own.
    """
    global _KNOWN_SKILLS
    if _KNOWN_SKILLS is not None:
        return _KNOWN_SKILLS
    sources = []
    override = os.environ.get("AGORA_SKILL_NAMES_FILE")
    if override:
        sources.append(Path(override))
    index = registry_index_path()
    if index:
        sources.append(index)
    sources.append(Path(__file__).resolve().parent / SKILL_NAMES_FILE)
    for source in sources:
        names = load_skill_names(source)
        if names:
            _KNOWN_SKILLS = names
            return names
    _KNOWN_SKILLS = set()
    return _KNOWN_SKILLS


def load_plugin_names(path: Path) -> set[str]:
    """Names from either the marketplace manifest or the shipped name list."""
    try:
        with open(path) as f:
            data = json.load(f)
    except (OSError, json.JSONDecodeError):
        return set()
    if not isinstance(data, dict):
        return set()
    if isinstance(data.get("plugins"), list):
        return {
            p["name"]
            for p in data["plugins"]
            if isinstance(p, dict) and isinstance(p.get("name"), str)
        }
    if isinstance(data.get("names"), list):
        return {n for n in data["names"] if isinstance(n, str)}
    return set()


_KNOWN_PLUGINS: set[str] | None = None


def known_plugin_names() -> set[str]:
    """Plugin names this marketplace owns.

    Fails CLOSED for the same reason known_skill_names() does: with no plugin
    list, no invocation can be attributed to the Agora, so capture records
    nothing.

    Sources, in order: an explicit AGORA_PLUGIN_NAMES_FILE override (tests),
    the marketplace manifest, then plugin-names.json shipped beside this
    script so the plugin-cache layout — which has no marketplace root above
    it — has a list of its own.
    """
    global _KNOWN_PLUGINS
    if _KNOWN_PLUGINS is not None:
        return _KNOWN_PLUGINS
    sources = []
    override = os.environ.get("AGORA_PLUGIN_NAMES_FILE")
    if override:
        sources.append(Path(override))
    manifest = marketplace_manifest_path()
    if manifest:
        sources.append(manifest)
    sources.append(Path(__file__).resolve().parent / PLUGIN_NAMES_FILE)
    for source in sources:
        names = load_plugin_names(source)
        if names:
            _KNOWN_PLUGINS = names
            return names
    _KNOWN_PLUGINS = set()
    return _KNOWN_PLUGINS


def agora_skill_name(qualified: str) -> str | None:
    """The bare skill name, when the invocation provably belongs to the Agora.

    Hook payloads name a skill or subagent by its owning plugin
    ("development:commit", "research-agents:devils-advocate"). Matching the
    bare tail against the registry attributes a personal skill to the Agora
    whenever the names collide: a user's own ~/.claude/commands/commit.md is
    invoked as ``commit``, which is also the name of the development plugin's
    skill, and the collision put personal usage into a public issue. So
    provenance comes from the prefix, and the three shapes resolve as:

    - ``<agora-plugin>:<skill>`` — Agora, once the tail is in the registry.
    - ``<other-plugin>:<skill>`` — another marketplace's; drop it.
    - ``<skill>`` — unattributable, so dropped too. This is narrower than the
      filter issue #25 installed, deliberately: a bare name is evidence of
      nothing, and capture that cannot prove provenance records nothing.

    The rule applies per invocation, never per session: a personal command
    that dispatches ``research-agents:devils-advocate`` is itself bare and
    dropped, while the Agora agent it dispatches stays attributable and is
    recorded.
    """
    plugin, separator, bare = qualified.partition(":")
    if not separator:
        return None
    if plugin not in known_plugin_names():
        return None
    if bare not in known_skill_names():
        return None
    return bare


def detect_error_code(text: str) -> str | None:
    for code in ERROR_CODES:
        if code in text:
            return code
    return None


def event_from_hook_payload(payload: dict) -> dict | None:
    """Translate a Claude Code hook payload into a spool event, or None."""
    hook_event = payload.get("hook_event_name", "")
    session = str(payload.get("session_id", ""))[:8] or "unknown"

    if hook_event == "SessionEnd":
        return {"event": "session_end", "session": session}

    tool = payload.get("tool_name", "")
    tool_input = payload.get("tool_input") or {}
    if tool == "Skill":
        skill = tool_input.get("skill") or tool_input.get("name")
        event_type = "invocation"
    elif tool in ("Task", "Agent"):
        skill = tool_input.get("subagent_type")
        event_type = "subagent"
    else:
        return None
    if not skill:
        return None

    skill = agora_skill_name(str(skill))
    if skill is None:
        return None  # unattributable, foreign, or no name list: record nothing

    response = payload.get("tool_response")
    response_text = (
        json.dumps(response)
        if isinstance(response, (dict, list))
        else str(response or "")
    )
    error_code = detect_error_code(response_text)
    if isinstance(response, dict) and ("error" in response or response.get("is_error")):
        outcome = "error"
    elif error_code == "PARTIAL_RESULT":
        outcome = "partial"
    elif error_code:
        outcome = "error"
    else:
        outcome = "success"

    return {
        "event": event_type,
        "session": session,
        "skill": skill,
        "outcome": outcome,
        "error_code": error_code,
        "duration_bucket": None,
        "model": None,
    }


def write_spool_lines(lines: list[str]) -> None:
    """Replace the spool atomically, the way purge_unknown_skills does.

    A temp file in the same directory plus os.replace() means a crash
    mid-write leaves the previous spool intact. The pid suffix keeps two
    concurrent rewrites from sharing one temp path.
    """
    spool = spool_path()
    secure_mkdir(spool.parent)
    tmp = spool.with_suffix(f".{os.getpid()}.tmp")
    tmp.write_text("".join(f"{line}\n" for line in lines))
    os.replace(tmp, spool)


def prune_spool() -> None:
    """Drop events older than the retention window from DISK.

    read_spool() filtered by age at read time, so the 90-day rolling
    retention of RFC-0001 §7 held in memory only: a user who enabled capture
    and never submitted kept every event on disk forever, since the spool
    file shrank only when a successful submit archived it (finding 6).

    Lines whose timestamp is missing or unparseable go with the expired ones.
    They can never enter a report — read_spool() already discards them — so
    keeping them live would grow the file without bound.
    """
    spool = spool_path()
    if not spool.exists():
        return
    cutoff = datetime.now().timestamp() - SPOOL_RETENTION_DAYS * 86400
    kept = []
    dropped = 0
    for line in spool.read_text().splitlines():
        if not line.strip():
            continue
        try:
            fresh = datetime.fromisoformat(json.loads(line)["ts"]).timestamp() >= cutoff
        except (json.JSONDecodeError, KeyError, TypeError, ValueError):
            fresh = False
        if fresh:
            kept.append(line)
        else:
            dropped += 1
    if dropped:
        write_spool_lines(kept)


def prune_due() -> bool:
    """True at most once per SPOOL_PRUNE_INTERVAL_SECONDS.

    Rewriting the spool on every captured event would put a full file rewrite
    in the hot path of every skill invocation, which RFC-0001 §4.4 forbids.
    Stamping first means a failed prune waits for the next interval instead
    of retrying on every event.
    """
    stamp = prune_stamp_path()
    try:
        if time.time() - stamp.stat().st_mtime < SPOOL_PRUNE_INTERVAL_SECONDS:
            return False
    except OSError:
        pass
    try:
        stamp.parent.mkdir(parents=True, exist_ok=True)
        stamp.touch()
    except OSError:
        return False
    return True


def cmd_capture() -> int:
    """Hook entry point. Must never fail and never block."""
    try:
        if not capture_enabled():
            return 0
        payload = json.load(sys.stdin)
        event = event_from_hook_payload(payload)
        if event is None:
            return 0
        event["ts"] = datetime.now().isoformat(timespec="seconds")
        secure_mkdir(spool_path().parent)
        with open(spool_path(), "a") as f:
            f.write(json.dumps(event) + "\n")
        # Retention runs here, throttled, and inside this blanket guard: a
        # failed prune can neither change the hook's exit code nor lose the
        # event just appended.
        if prune_due():
            prune_spool()
    except Exception:
        pass
    return 0


def read_spool() -> list[dict]:
    events = []
    try:
        with open(spool_path()) as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    events.append(json.loads(line))
                except json.JSONDecodeError:
                    continue
    except OSError:
        return []
    cutoff = datetime.now().timestamp() - SPOOL_RETENTION_DAYS * 86400
    kept = []
    for e in events:
        try:
            if datetime.fromisoformat(e["ts"]).timestamp() >= cutoff:
                kept.append(e)
        except (KeyError, ValueError):
            continue
    return kept


def aggregate_spool(events: list[dict]) -> dict:
    """Per-skill counters from spool events (day precision, content-free)."""
    skills: dict[str, dict] = {}
    sessions = set()
    days = []
    for e in events:
        sessions.add(e.get("session"))
        days.append(e["ts"][:10])
        if e.get("event") == "session_end":
            continue
        s = skills.setdefault(
            e["skill"],
            {
                "invocations": 0,
                "outcomes": {"success": 0, "partial": 0, "error": 0, "unknown": 0},
                "error_codes": {},
                "duration_buckets": {},
                "models": {},
            },
        )
        s["invocations"] += 1
        s["outcomes"][e.get("outcome", "unknown")] = (
            s["outcomes"].get(e.get("outcome", "unknown"), 0) + 1
        )
        for key, field in (
            ("error_code", "error_codes"),
            ("duration_bucket", "duration_buckets"),
            ("model", "models"),
        ):
            value = e.get(key)
            if value:
                s[field][value] = s[field].get(value, 0) + 1
    return {
        "skills": skills,
        "sessions": len(sessions),
        "from": min(days) if days else None,
        "to": max(days) if days else None,
    }


def git_short_sha(repo: Path, path: str | None = None) -> str | None:
    cmd = ["git", "-C", str(repo), "log", "-1", "--format=%h"]
    if path:
        cmd += ["--", path]
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=10)
        sha = out.stdout.strip()
        return sha or None
    except (OSError, subprocess.SubprocessError):
        return None


def events_cutoff(events: list[dict]) -> str | None:
    """Newest full-precision timestamp among the events a report covers.

    Submission archives up to this mark, so events captured after the report
    was built stay live for the next cycle (finding 7).
    """
    stamps = [e["ts"] for e in events if isinstance(e.get("ts"), str)]
    return max(stamps) if stamps else None


def build_report(events: list[dict] | None = None) -> dict:
    """Assemble the report payload from spool events.

    Callers that also need the coverage cutoff pass the same event list they
    read, so the cutoff describes exactly the events the report counted.
    """
    config = load_config()
    events = read_spool() if events is None else events
    agg = aggregate_spool(events)
    root = marketplace_root()

    skill_entries = []
    for name in sorted(agg["skills"]):
        counters = agg["skills"][name]
        entry = {"skill": name, "skill_sha": None, **counters, "insights": []}
        skill_entries.append(entry)

    marketplace_sha = git_short_sha(root) if root else None
    if marketplace_sha:
        paths = {}
        try:
            with open(registry_index_path()) as f:
                for repo in json.load(f).get("repos", []):
                    for s in repo.get("skills", []):
                        paths[s["name"]] = s.get("path")
        except (OSError, TypeError, json.JSONDecodeError):
            pass
        for entry in skill_entries:
            skill_file = paths.get(entry["skill"])
            if skill_file:
                entry["skill_sha"] = git_short_sha(root, skill_file)

    return {
        "schema_version": SCHEMA_VERSION,
        "report_id": f"r-{uuid.uuid4()}",
        "created": date.today().isoformat(),
        "reporter": {
            "installation_id": config.get("installation_id"),
            "client": "claude-code",
            "marketplace_sha": marketplace_sha,
        },
        "period": {"from": agg["from"], "to": agg["to"], "sessions": agg["sessions"]},
        "consent": {
            "reviewed": False,
            "channel": config.get("sink", "github-issue"),
            "policy_version": POLICY_VERSION,
        },
        "skills": skill_entries,
        "environment": {"os": sys.platform},
    }


def pii_findings(report: dict) -> list[str]:
    findings = []
    for entry in report.get("skills", []):
        for insight in entry.get("insights", []):
            for label, pattern in PII_PATTERNS:
                if pattern.search(insight.get("text", "")):
                    findings.append(
                        f"{entry['skill']}: insight contains {label}: {insight['text'][:80]!r}"
                    )
    return findings


def control_char_findings(report: dict) -> list[str]:
    """Strings in the payload carrying control characters (finding 3).

    The scan covers every string in the payload rather than insight text
    alone, because the whole payload is what gets published, and a
    hand-edited pending report is not bound by the insight-add check.
    """
    findings = []

    def walk(node, path: str) -> None:
        if isinstance(node, dict):
            for key, value in node.items():
                walk(value, f"{path}.{key}" if path else str(key))
        elif isinstance(node, list):
            for index, value in enumerate(node):
                walk(value, f"{path}[{index}]")
        elif isinstance(node, str) and CONTROL_CHARS_RE.search(node):
            findings.append(f"{path or 'payload'}: control characters in {node[:80]!r}")

    walk(report, "")
    return findings


